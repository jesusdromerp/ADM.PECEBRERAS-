export function calculateMetrics(
  pesebreras: Pesebrera[],
  horses: Horse[],
  clients: Client[],
  payments: PaymentRecord[]
): DashboardMetrics {
  const totalBoxes = pesebreras.length;
  const occupiedBoxes = pesebreras.filter((b) => b.status === "ocupada").length;
  const availableBoxes = pesebreras.filter((b) => b.status === "disponible").length;
  const occupancyRate = totalBoxes > 0 ? Math.round((occupiedBoxes / totalBoxes) * 100) : 0;

  const totalHorses = horses.length;
  const horsesInTreatment = horses.filter(
    (h) => h.healthStatus === "en_tratamiento" || h.healthStatus === "reposo"
  ).length;

  const activeClients = clients.length;

  const monthlyRevenue = payments
    .filter((p) => p.status === "pagado")
    .reduce((acc, curr) => acc + curr.amount, 0);

  const pendingPayments = payments.filter((p) => p.status !== "pagado");
  const pendingPaymentsCount = pendingPayments.length;
  const pendingPaymentsTotal = pendingPayments.reduce((acc, curr) => acc + curr.amount, 0);

  return {
    totalBoxes,
    occupiedBoxes,
    availableBoxes,
    occupancyRate,
    totalHorses,
    horsesInTreatment,
    activeClients,
    monthlyRevenue,
    pendingPaymentsCount,
    pendingPaymentsTotal,
  };
}
